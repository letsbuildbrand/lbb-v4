function getWeek(day) {
  if (day <= 7) return 1;
  if (day <= 14) return 2;
  if (day <= 20) return 3;
  if (day <= 26) return 4;
  if (day <= 30) return 5;
  return 6;
}

function buildDayCard(day) {
  const num = String(day.day).padStart(2, '0');
  const tagsHTML = day.tags.map(t => `<span class="form-tag ${t.cls}">${t.label} | ${t.text}</span>`).join('');
  const detailsHTML = day.details.map(d => `<div class="form-detail-block"><div class="label">${d.label}</div><div class="value">${d.value}</div></div>`).join('');

  return `
  <div class="day-card" onclick="toggleDay(this)">
    <div class="day-header">
      <div class="day-number">${num}</div>
      <div class="day-title">${day.title}</div>
      <div class="day-type ${day.type}">${day.type.charAt(0).toUpperCase() + day.type.slice(1)}</div>
      <div class="day-toggle">+</div>
    </div>
    <div class="day-body">
      <div class="form-tags">${tagsHTML}</div>
      <div class="form-detail">${detailsHTML}</div>
      <div class="impact-row">
        <div class="impact-icon">${day.impactIcon}</div>
        <div class="impact-text">${day.impact}</div>
      </div>
    </div>
  </div>`;
}

function renderCalendar() {
  const container = document.getElementById('calendar-days');
  if (!container) return;

  let html = '';
  let currentWeek = 0;

  CALENDAR_DATA.forEach(day => {
    const week = getWeek(day.day);
    if (week !== currentWeek) {
      if (currentWeek !== 0) html += '</div>';
      const weekInfo = WEEK_LABELS[week];
      html += `<div class="week-label visible">${weekInfo.label}</div><div class="calendar-week" data-phase="${weekInfo.phase}">`;
      currentWeek = week;
    }
    html += buildDayCard(day);
  });

  if (currentWeek !== 0) html += '</div>';
  container.innerHTML = html;
}

document.addEventListener('DOMContentLoaded', () => {
  const container = document.getElementById('calendar-days');
  if (!container) return;
  renderCalendar();
  if (window._sharedObserver) {
    container.querySelectorAll('.reveal').forEach(el => window._sharedObserver.observe(el));
  }
});
